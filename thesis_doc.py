def load() -> tuple:
    """Return (metrics, panel, forecasts, tripwires, manifest) parsed from the current directory."""
    with open("out/metrics.json") as f:
        m = json.load(f)
    with open("out/panel.json") as f:
        p = json.load(f)
    with open("forecasts.json") as f:
        fc = json.load(f)
    with open("tripwires.json") as f:
        t = json.load(f)
    with open("data/MANIFEST.json") as f:
        man = json.load(f)
    return m, p, fc, t, man


def money(v: float) -> str:
    """Format a dollar amount: >=1e9 -> "$X.XX billion", >=1e6 -> "$X.X million", else "$X,XXX"."""
    if abs(v) >= 1e9:
        return f"${v / 1e9:,.2f} billion"
    if abs(v) >= 1e6:
        return f"${v / 1e6:,.1f} million"
    return f"${v:,.0f}"


def big(v: float) -> str:
    """Format a large number: >= 1e6 -> X.X million, else Y,YYY."""
    if abs(v) >= 1e6:
        return f"{v / 1e6:,.1f} million"
    return f"{v:,.0f}"


def table(rows: list, results: list) -> str:
    """Build a Markdown tripwire + forecast table from row dicts and score results."""
    lines = ["| ID | Statement | Metric | Test | Today | On track? | Due |"]
    lines.append("|---|---|---|---|---|---|---|")
    for row, sc in zip(rows, results):
        v = sc["value"]
        val = "no data" if v is None else (f"{v:,.0f}" if abs(v) >= 100 else f"{v:,.3g}")
        lines.append(
            f"| {row['id']} | {row['statement']} | `{row['path']}` | {row['op']} {row['threshold']:,} | {val} | {sc['status']} | {row['due']} |"
        )
    return "\n".join(lines) + "\n"


def src(man: dict, name: str) -> str:
    """Return man[name]['url']; raises KeyError when absent."""
    return man[name]["url"]


