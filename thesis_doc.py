def models_table(p: dict) -> str:
    """Return a Markdown table of judge model names and makers from p['judges'].""" 
    header = "| Judge model | Maker |"
    separator = "|---|---|"
    rows = []
    for entry in p["judges"]:
        model = entry.split(" (")[0]
        paren_idx = entry.find("(")
        if paren_idx == -1:
            maker = ""
        else:
            inner = entry[paren_idx+1:]
            end_paren = inner.find(")")
            if end_paren != -1:
                inner = inner[:end_paren]
            comma_idx = inner.find(",")
            if comma_idx != -1:
                maker = inner[:comma_idx].strip()
            else:
                maker = inner.strip()
        rows.append(f"| {model} | {maker} |")
    return "\n".join([header, separator] + rows)


def readme_synced(text: str, p: dict) -> str:
    """Replace <!-- MODELS:BEGIN -->...<!-- MODELS:END --> in *text* with models_table(p).

    Raises ValueError when either marker is missing, repeated or out of order.
    """
    begin = "<!-- MODELS:BEGIN -->"
    end = "<!-- MODELS:END -->"
    begin_count = text.count(begin)
    end_count = text.count(end)
    if begin_count != 1:
        raise ValueError(f"found {begin_count} MODELS:BEGIN markers")
    if end_count != 1:
        raise ValueError(f"found {end_count} MODELS:END markers")
    begin_index = text.find(begin)
    end_index = text.find(end)
    if begin_index >= end_index:
        raise ValueError("MODELS:BEGIN after MODELS:END")
    # Find the end of the begin line and start of the end line to preserve spacing
    begin_line_end = text.find('\n', begin_index) + 1
    end_line_start = text.rfind('\n', 0, end_index) + 1
    # Generate replacement content
    table = models_table(p)
    # Replace everything between begin_line_end and end_line_start
    result = text[:begin_line_end] + table + "\n" + text[end_line_start:]
    return result


def main(argv: Optional[list] = None) -> int:
    """Entry point: with --check compare generated docs to disk; otherwise write them."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)

    m, p, f, t, man = load()
    want = {
        "THESIS.md": thesis(m, p, f, t),
        "TRIPWIRES.md": tripwires(m, p, f, t, man),
        "WEAKNESSES.md": weaknesses(m, p, f, t, man)
    }

    readme_updated = False
    try:
        with open("README.md") as fh:
            readme_text = fh.read()
        synced_text = readme_synced(readme_text, p)
        if synced_text != readme_text:
            readme_updated = True
    except (FileNotFoundError, ValueError):
        readme_updated = True

    if args.check:
        stale = []
        for name, content in want.items():
            try:
                with open(name) as fh:
                    disk_content = fh.read()
                if disk_content != content:
                    stale.append(name)
            except FileNotFoundError:
                stale.append(name)
        
        if readme_updated:
            stale.append("README.md")

        if stale:
            # Preserve order
            ordered_stale = []
            for fname in ["THESIS.md", "TRIPWIRES.md", "WEAKNESSES.md", "README.md"]:
                if fname in stale:
                    ordered_stale.append(fname)
            
            print(f"DOCS OUT OF DATE: {', '.join(ordered_stale)} (run: python3 thesis_doc.py)")
            return 1
        
        print("DOCS OK: THESIS.md, TRIPWIRES.md and WEAKNESSES.md match the committed numbers")
        return 0
    
    # Write output
    for name, content in want.items():
        with open(name, "w") as fh:
            fh.write(content)
        print(f"wrote {name} {len(content)}")
    
    if readme_updated:
        with open("README.md", "w") as fh:
            fh.write(synced_text)
        print(f"wrote README.md {len(synced_text)}")
    
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
